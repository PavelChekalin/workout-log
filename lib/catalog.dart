// Названия упражнений пользователь пишет сам, поэтому привязка к справочнику
// не автоматическая: приложение ПОДСКАЗЫВАЕТ запись по введённому названию,
// а человек подтверждает выбор. Описания техники — свои (не из чужих
// приложений). Позже сюда добавятся схематичные рисунки.
// ---------------------------------------------------------------------------

/// Запись справочника: название, ключевые слова для подсказки, мышцы и текст.
class TechEntry {
  final String id;
  final String name;
  final List<String> keywords;
  final String muscles;
  final String technique;
  const TechEntry({
    required this.id,
    required this.name,
    required this.keywords,
    required this.muscles,
    required this.technique,
  });
}

TechEntry? techById(String? id) {
  if (id == null) return null;
  for (final t in kTechCatalog) {
    if (t.id == id) return t;
  }
  return null;
}

/// Подбор техники по введённому названию (до 4 вариантов, самые близкие сверху).
List<TechEntry> suggestTech(String name) {
  final n = name.toLowerCase().trim();
  if (n.isEmpty) return const [];
  final exact = <TechEntry>[];
  final partial = <TechEntry>[];
  for (final t in kTechCatalog) {
    if (t.name.toLowerCase() == n) {
      exact.add(t);
      continue;
    }
    for (final k in t.keywords) {
      if (n.contains(k)) {
        partial.add(t);
        break;
      }
    }
  }
  return [...exact, ...partial].take(4).toList();
}

