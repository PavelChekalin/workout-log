/// Случайная фраза по событию и тону. Для неизвестного тона — «Тренер».
String? coachLine(String tone, String event, {Random? random}) {
  final byTone = kCoachLines[event]?[tone] ??
      kCoachLines[event]?[CoachTone.coach];
  if (byTone == null || byTone.isEmpty) return null;
  return byTone[(random ?? Random()).nextInt(byTone.length)];
}
